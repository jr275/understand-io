import type { AiResult, Coverage, Gloss, GlossDocument, SummaryVariant } from "@/lib/content/types";
import { languageName } from "./languages";

export const STRUCTURED_ACTIONS = ["summarize", "translate", "concepts", "questions"] as const;

/** A gloss that is a structured result (summary, translation, ...) rather than a streamed answer in the margin. */
export const isInsight = (g: Pick<Gloss, "action">) => (STRUCTURED_ACTIONS as readonly string[]).includes(g.action);

export const VARIANT_LABEL: Record<SummaryVariant, string> = { quick: "Quick summary", executive: "Executive summary", detailed: "Detailed summary", ideas: "Key ideas", passage: "Summary of a passage" };

export function insightTitle(r: AiResult): string {
  if (r.kind === "summary") return VARIANT_LABEL[r.variant];
  if (r.kind === "concepts") return "Key concepts";
  if (r.kind === "questions") return "Questions to check your understanding";
  return `Translation to ${languageName(r.targetLang)}`;
}

/** The plain sentence that says which part of the text a result is based on (shown on every card and in exports). */
export function coverageLine(c: Coverage): string {
  if (c.complete) return `Based on the whole text (${c.total} paragraph${c.total === 1 ? "" : "s"}).`;
  if (c.note && !c.used) return c.note;
  if (c.note) return c.note;
  return `Based on ${c.used} of ${c.total} paragraphs.`;
}

/** Markdown for copying or downloading a result. Quotes stay marked as quotes, interpretation stays marked as interpretation. */
export function insightMarkdown(g: Gloss, doc: Pick<GlossDocument, "title" | "author" | "sourceUrl">): string {
  const r = g.result;
  if (!r || r.kind === "stream") return "";
  const lines: string[] = [`# ${insightTitle(r)}`, "", `Text: ${doc.title}${doc.author ? `, ${doc.author}` : ""}${doc.sourceUrl ? ` (${doc.sourceUrl})` : ""}`, `Generated by an AI model${g.model ? ` (${g.model})` : ""} on ${new Date(g.createdAt).toISOString().slice(0, 10)}. Not written by the author.`, ""];
  if (r.kind === "translation") {
    lines.push(`## Original (${r.sourceLang || "unknown language"})`, "", ...r.original.split("\n").map((l) => `> ${l}`), "", `## Translation (${languageName(r.targetLang)})`, "", r.natural, "");
    if (r.literal) lines.push("### Literal rendering", "", r.literal, "");
    if (r.notes.length) lines.push("### Notes", "", ...r.notes.map((n) => `- ${n}`), "");
    return lines.join("\n");
  }
  lines.push(`_${coverageLine(r.coverage)}_`, "");
  for (const it of r.items) {
    const tag = it.basis === "interpretation" ? (it.unverified ? " _(interpretation, no quote could be verified)_" : " _(interpretation)_") : it.basis === "external" ? " _(from outside the text)_" : "";
    lines.push(`- ${it.label ? `**${it.label}.** ` : ""}${it.text}${tag}`);
    if (it.answer) lines.push(`  - Answer: ${it.answer}`);
    for (const e of it.evidence) lines.push(`  - ${e.n ? `¶${e.n}: ` : ""}“${e.quote}”`);
  }
  if (r.caveats.length) lines.push("", "Limits:", ...r.caveats.map((c) => `- ${c}`));
  return lines.join("\n") + "\n";
}
