#!/usr/bin/env node
// Rebuilds docs/legal/OPEN_ITEMS.md from the ⚠️ markers in the legal texts, so the list can never drift from the texts.
//
//   node scripts/legal-open-items.mjs          write docs/legal/OPEN_ITEMS.md
//   node scripts/legal-open-items.mjs --check  fail if the file is out of date, or the two languages carry different markers
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "docs", "legal");
const TEXTS = [
  ["privacy-policy", "Privacy Policy"],
  ["terms-of-use", "Terms of Use"],
  ["ai-notice", "AI and third-party providers"],
  ["retention-and-deletion", "Retention and deletion"],
  ["beta-notice", "Beta notice"],
];
const kindOf = { en: { owner: "OWNER DECISION", legal: "LEGAL REVIEW" }, pt: { owner: "DECISÃO DO PROPRIETÁRIO", legal: "REVISÃO JURÍDICA" } };

function markers(file, lang) {
  const lines = fs.readFileSync(file, "utf8").split("\n");
  let section = "(top of the document)";
  const out = [];
  for (const line of lines) {
    const h = /^##\s+(.*)$/.exec(line);
    if (h) section = h[1].trim();
    const re = new RegExp(`⚠️ \\[(${kindOf[lang].owner}|${kindOf[lang].legal}): ([^\\]]*)\\]`, "g");
    for (const m of line.matchAll(re)) out.push({ section, kind: m[1] === kindOf[lang].owner ? "owner" : "legal", what: m[2].trim() });
  }
  return out;
}

const rows = [];
const problems = [];
for (const [slug, title] of TEXTS) {
  const en = markers(path.join(dir, `${slug}.en.md`), "en");
  const pt = markers(path.join(dir, `${slug}.pt-BR.md`), "pt");
  if (en.length !== pt.length || en.some((m, i) => m.kind !== pt[i].kind)) problems.push(`${slug}: ${en.length} markers in English, ${pt.length} in Portuguese (or different kinds)`);
  for (const m of en) rows.push({ title, ...m });
}

const owner = rows.filter((r) => r.kind === "owner");
const legal = rows.filter((r) => r.kind === "legal");
const count = (title, kind) => rows.filter((r) => r.title === title && r.kind === kind).length;
const table = (list) => ["| Text | Section | What is open |", "| --- | --- | --- |", ...list.map((r) => `| ${r.title} | ${r.section} | ${r.what.replace(/\|/g, "/")} |`)].join("\n");

const md = `# Open items in the legal texts

_Generated by \`scripts/legal-open-items.mjs\` from the ⚠️ markers in \`docs/legal/*.en.md\` (the Portuguese files must carry the same markers; the script checks it). Each marker is either an **owner decision** (a fact only the operator knows or chooses) or a **legal review item** (something a lawyer must confirm or word). Do not edit this file by hand._

**${owner.length} owner decisions and ${legal.length} legal review items** across ${TEXTS.length} texts (several repeat the same fact, for example the date at publication). Every text also carries the "draft, not legal advice" banner, which is removed only at publication.

| Text | Owner decisions | Legal review |
| --- | --- | --- |
${TEXTS.map(([, t]) => `| ${t} | ${count(t, "owner")} | ${count(t, "legal")} |`).join("\n")}

## Already settled by the owner (2026-10-29)

* Operator: **Menlo Software AIP** (name only: no registered address, registration number or legal form was given, and none is stated).
* Contact for privacy requests and feedback: **jm@useclave.io**.
* Business model: free, with limited daily use of the AI features (freemium); no payment feature exists.
* Hosting: Vercel Pro (functions in region \`iad1\`, Washington, D.C.); database: Neon Free; AI provider: Together AI; sign-in: Google.

## Owner decisions

${table(owner)}

## Legal review items

${table(legal)}

## Publishing

Nothing is shown to readers until \`GLOSS_LEGAL_PUBLISHED=1\` is set **and** no ⚠️ marker is left in either language of a text (see \`docs/legal/README.md\`).
`;

const target = path.join(dir, "OPEN_ITEMS.md");
if (process.argv.includes("--check")) {
  const same = fs.existsSync(target) && fs.readFileSync(target, "utf8") === md;
  if (problems.length || !same) {
    for (const p of problems) console.error(p);
    if (!same) console.error("docs/legal/OPEN_ITEMS.md is out of date: run node scripts/legal-open-items.mjs");
    process.exit(1);
  }
  console.log("OPEN_ITEMS.md is current.");
} else {
  if (problems.length) {
    for (const p of problems) console.error(p);
    process.exit(1);
  }
  fs.writeFileSync(target, md);
  console.log(`Wrote docs/legal/OPEN_ITEMS.md: ${owner.length} owner decisions, ${legal.length} legal review items.`);
}
